/**
 * build-law-change-digest.mjs — generate the `law-change-digest` n8n workflow JSON.
 *
 * G4 of specs/features/law-change-impact/ (Tier 2). Assembles the n8n workflow that turns a
 * `law_change_log` row (written `ai_status='pending'` with a deterministic `article_diffs` by
 * the Node monitor, G1) into a PRELIMINARY "what changed + per-service impact" draft for the
 * lawyer to review. Pipeline L2 → L3 → L4 → L5 (plan.md / requirements.md):
 *
 *   Triggers (Schedule hourly + Webhook for GH-Actions kick / manual test)
 *     → Global Config (keys, model, confidence threshold)
 *     → Fetch Pending / Fetch Chunks / Fetch Relations   (3 Supabase REST GETs, parallel)
 *     → Compute Scopes   (L2: per pending row → deterministic impact scope + Groq request body)
 *     → L3 Reasoning     (Groq: strict-JSON "what changed" draft, one call per pending row)
 *     → Critique & Decide(L4a deterministic groundedness + confidence gate → drafted/abstained/error)
 *     → Write Result     (Supabase REST PATCH: ai_summary/ai_impact/ai_confidence/ai_status/...)
 *
 * Anti-drift: the Code-node bodies are GENERATED here from single sources of truth —
 *   n8n/templates/law-change-scope.js          (L2 computeImpactScope + diffTouchesNumbers)
 *   n8n/templates/law-change-groundedness.js    (L4a checkLawChangeGroundedness)
 *   n8n/prompts/law-change-digest.txt           (L3 prompt)
 * Re-run this script after editing any of them, then deploy.
 *
 * SAFETY / honesty:
 *   - No n8n credentials: every secret is read from the Global Config node via expression
 *     (Authorization: Bearer {{GROQ_API_KEY}}; Supabase apikey/Bearer {{SUPABASE_SERVICE_KEY}}),
 *     so the workflow is fully self-contained and deploy = inject keys + PUT/POST. Global Config
 *     keeps YOUR_* placeholders in the repo (deploy-workflow.mjs injects the real keys in memory).
 *   - Advisory-only: the only column the digest writes are ai_* (never `notes`/`action`).
 *   - Degrade ≥ today: malformed/missing Groq JSON → ai_status='error'; low confidence or a RED
 *     groundedness span → ai_status='abstained' (no draft) — the deterministic article_diffs and
 *     the needs_review flip (done earlier by the monitor) always stand.
 *   - LLM-critic L4b (n8n/prompts/law-change-critic.txt) is intentionally NOT wired here: it only
 *     adds advisory AMBER and never gates (requirements §3.3). Deferred to keep v1 lean; the
 *     deterministic L4a + confidence threshold is the real safety gate.
 *
 * Usage:  node scripts/build-law-change-digest.mjs [--check]
 *           --check   exit 1 if the generated JSON differs from the committed file (CI guard)
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..');
const outPath = resolve(repoRoot, 'n8n/workflows/current/law-change-digest.json');
const checkOnly = process.argv.includes('--check');

const read = (p) => readFileSync(resolve(repoRoot, p), 'utf8').replace(/\r\n/g, '\n');

// ─── SSoT sources (inlined into Code nodes) ──────────────────────────────────
const SCOPE_SRC = read('n8n/templates/law-change-scope.js');
const GROUNDEDNESS_SRC = read('n8n/templates/law-change-groundedness.js');
const DIGEST_PROMPT = read('n8n/prompts/law-change-digest.txt');

// ─── Global Config (mirror form-submit; only the keys this workflow needs) ────
const GLOBAL_CONFIG_CODE = [
  '// ═══════════════════════════════════════════════════════',
  '// GLOBAL CONFIG — law-change-digest. Keys injected by scripts/deploy-workflow.mjs.',
  '// ═══════════════════════════════════════════════════════',
  'return [{ json: {',
  "  SUPABASE_URL:         'https://nexkairsedqtczievxpa.supabase.co',",
  "  SUPABASE_SERVICE_KEY: 'YOUR_SUPABASE_SERVICE_ROLE_KEY',",
  "  GROQ_API_KEY:         'YOUR_GROQ_API_KEY',",
  "  GROQ_MODEL:           'llama-3.3-70b-versatile',",
  "  // Abstention threshold (requirements §3.3): overall_confidence below this → no draft.",
  "  CONFIDENCE_THRESHOLD: '0.5',",
  '}}];',
].join('\n');

// ─── Compute Scopes (L2) — per pending row → scope + Groq request body ────────
const COMPUTE_SCOPES_CODE = [
  '// ═══════════════════════════════════════════════════════',
  '// Compute Scopes (L2) — GENERATED by scripts/build-law-change-digest.mjs',
  '// Edit n8n/templates/law-change-scope.js / n8n/prompts/law-change-digest.txt and re-run.',
  '// ═══════════════════════════════════════════════════════',
  '',
  '// L2 scope (mirror: n8n/templates/law-change-scope.js)',
  SCOPE_SRC,
  '',
  'const DIGEST_PROMPT_TEMPLATE = ' + JSON.stringify(DIGEST_PROMPT) + ';',
  '',
  'function fillDigestPrompt(t, c) {',
  "  return t",
  "    .replace('{{LAW_TITLE}}',        c.LAW_TITLE)",
  "    .replace('{{LAW_CODE}}',         c.LAW_CODE)",
  "    .replace('{{CHANGED_ARTICLES}}', c.CHANGED_ARTICLES)",
  "    .replace('{{DIFF_HUNKS}}',       c.DIFF_HUNKS)",
  "    .replace('{{SCOPE_SERVICES}}',   c.SCOPE_SERVICES)",
  "    .replace('{{ALLOWED_ARTICLES}}', c.ALLOWED_ARTICLES)",
  "    .replace('{{ALLOWED_SLUGS}}',    c.ALLOWED_SLUGS);",
  '}',
  '',
  '// law_chunks.article_num is stored as "Стаття 182"; article_diffs.changed_articles are bare',
  '// numbers ("182"). Normalise chunk article numbers so computeImpactScope can match them.',
  "const artNum = (a) => { const m = String(a == null ? '' : a).match(/\\d+(?:-\\d+)?/); return m ? m[0] : ''; };",
  '',
  '// n8n entry point. The fetch nodes run on a linear spine with alwaysOutputData, so an',
  '// empty result still emits a placeholder item — filter those out by real-row shape.',
  "const pending   = $('Fetch Pending').all().map((i) => i.json).filter((r) => r && r.id != null && r.article_diffs);",
  "const chunksRaw = $('Fetch Chunks').all().map((i) => i.json).filter((c) => c && c.article_num != null);",
  "const relations = $('Fetch Relations').all().map((i) => i.json).filter((r) => r && r.relation_type);",
  "const model     = $('Global Config').first().json.GROQ_MODEL || 'llama-3.3-70b-versatile';",
  '',
  'const chunks = chunksRaw.map((c) => ({ ...c, article_num: artNum(c.article_num) }));',
  '',
  'const out = [];',
  'for (const row of pending) {',
  '  const ad = row.article_diffs || {};',
  '  const changedArticles = (ad.changed_articles || []).map(String);',
  '  const scope = computeImpactScope({',
  '    changedArticles,',
  '    lawCode: ad.law_code,',
  '    lawChunks: chunks,',
  '    lawRelations: relations,',
  '    touchesNumbers: diffTouchesNumbers(ad),',
  '  });',
  '',
  '  const allowedArticles = [...new Set([...changedArticles, ...scope.norms.map(String)])];',
  '  const allowedSlugs = scope.services.map((s) => s.slug);',
  '',
  '  // Present removed/added lines VERBATIM (no inline +/− markers) under labelled blocks so',
  '  // the model can copy an `evidence` line exactly — the deterministic critic matches it',
  '  // character-for-character against the raw diff corpus.',
  '  const diffText = (ad.hunks || [])',
  '    .map((h) => {',
  "      const rem = (h.removed || []).length ? 'ВИЛУЧЕНО:\\n' + h.removed.join('\\n') : '';",
  "      const add = (h.added || []).length ? 'ДОДАНО:\\n' + h.added.join('\\n') : '';",
  "      return '[ст.' + (h.article_num || '?') + ' | ' + (h.op || 'changed') + ']\\n' + [rem, add].filter(Boolean).join('\\n');",
  '    })',
  "    .join('\\n\\n');",
  '',
  '  const scopeText = scope.services.length',
  "    ? scope.services.map((s) => '- ' + s.slug + ' (стеля severity: ' + s.severity + '; статті: ' + s.articles.join(', ') + ')').join('\\n')",
  "    : '(жодної послуги в scope)';",
  '',
  '  const prompt = fillDigestPrompt(DIGEST_PROMPT_TEMPLATE, {',
  "    LAW_TITLE:        row.law_title || ad.law_code || '',",
  "    LAW_CODE:         ad.law_code || '',",
  "    CHANGED_ARTICLES: changedArticles.join(', ') || '(невідомо)',",
  "    DIFF_HUNKS:       diffText || '(порожній diff)',",
  '    SCOPE_SERVICES:   scopeText,',
  "    ALLOWED_ARTICLES: allowedArticles.join(', ') || '(порожньо)',",
  "    ALLOWED_SLUGS:    allowedSlugs.join(', ') || '(порожньо)',",
  '  });',
  '',
  '  out.push({ json: {',
  '    _row_id: row.id,',
  '    _article_diffs: ad,',
  '    _scope: scope,',
  '    _allowed_slugs: allowedSlugs,',
  '    _model: model,',
  '    _groq_body: {',
  '      model,',
  '      temperature: 0.2,',
  "      response_format: { type: 'json_object' },",
  "      messages: [{ role: 'user', content: prompt }],",
  '    },',
  '  } });',
  '}',
  'return out;',
].join('\n');

// ─── Critique & Decide (L4) — groundedness + confidence gate → PATCH payload ──
const CRITIQUE_CODE = [
  '// ═══════════════════════════════════════════════════════',
  '// Critique & Decide (L4) — GENERATED by scripts/build-law-change-digest.mjs',
  '// Edit n8n/templates/law-change-groundedness.js and re-run.',
  '// ═══════════════════════════════════════════════════════',
  '',
  '// L4a deterministic groundedness (mirror: n8n/templates/law-change-groundedness.js)',
  GROUNDEDNESS_SRC,
  '',
  '// n8n entry point (one item per pending row; row context via paired item):',
  "const ctx = $('Compute Scopes').item.json;",
  "const threshold = parseFloat($('Global Config').first().json.CONFIDENCE_THRESHOLD || '0.5');",
  'const nowIso = new Date().toISOString();',
  'const base = { _row_id: ctx._row_id, _model: ctx._model, _generated_at: nowIso };',
  '',
  '// Parse the Groq strict-JSON response. Malformed/missing → error (diff still stands).',
  'let draft = null;',
  'try {',
  '  const content = $json.choices && $json.choices[0] && $json.choices[0].message && $json.choices[0].message.content;',
  '  draft = JSON.parse(content);',
  '} catch (e) {',
  "  return [{ json: { ...base, _status: 'error', _summary: null, _impact: null, _confidence: null } }];",
  '}',
  'if (!draft || typeof draft !== "object") {',
  "  return [{ json: { ...base, _status: 'error', _summary: null, _impact: null, _confidence: null } }];",
  '}',
  '',
  '// L4a — deterministic groundedness against the diff + L2 scope.',
  'const g = checkLawChangeGroundedness(draft, { articleDiffs: ctx._article_diffs, scope: ctx._scope });',
  "const conf = typeof draft.overall_confidence === 'number' ? draft.overall_confidence : 0;",
  '',
  '// Clamp per-service severity to the deterministic L2 ceiling (LLM may go lower, never higher).',
  'const RANK = { low: 1, medium: 2, high: 3 };',
  'const ceil = {};',
  'for (const s of (ctx._scope.services || [])) ceil[s.slug] = s.severity;',
  'const clampedImpact = (draft.per_service || []).map((it) => {',
  '  const c = ceil[it.slug];',
  '  let sev = it.severity;',
  '  if (c && RANK[sev] > RANK[c]) sev = c;',
  '  return { ...it, severity: sev };',
  '});',
  '',
  '// Abstention (requirements §3.3): a RED span OR confidence below threshold → no draft.',
  'if (g.has_red || conf < threshold) {',
  "  return [{ json: { ...base, _status: 'abstained', _summary: null, _impact: null, _confidence: conf } }];",
  '}',
  '',
  "return [{ json: { ...base, _status: 'drafted', _summary: draft.summary || null, _impact: clampedImpact, _confidence: conf } }];",
].join('\n');

