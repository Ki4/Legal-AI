// ─── Connections ──────────────────────────────────────────────────────────────
// LINEAR spine (not a fan-out): n8n's v1 execution order is depth-first and does NOT wait
// for sibling branches, so parallel fetches would let Compute Scopes run before they finish
// ("Node X hasn't been executed"). Chaining the fetches guarantees all three have executed —
// and are therefore queryable via $('Fetch X').all() — before Compute Scopes. The two later
// fetches carry executeOnce (fire once despite upstream fan-out) + alwaysOutputData (an empty
// result still passes one item along so the chain survives an empty graph / empty queue).
//   Triggers → Global Config → Fetch Chunks → Fetch Relations → Fetch Pending
//            → Compute Scopes → L3 Reasoning → Critique & Decide → Write Result
const connections = {
  'Schedule Trigger': { main: [[{ node: 'Global Config', type: 'main', index: 0 }]] },
  'Webhook Kick': { main: [[{ node: 'Global Config', type: 'main', index: 0 }]] },
  'Global Config': { main: [[{ node: 'Fetch Chunks', type: 'main', index: 0 }]] },
  'Fetch Chunks': { main: [[{ node: 'Fetch Relations', type: 'main', index: 0 }]] },
  'Fetch Relations': { main: [[{ node: 'Fetch Pending', type: 'main', index: 0 }]] },
  'Fetch Pending': { main: [[{ node: 'Compute Scopes', type: 'main', index: 0 }]] },
  'Compute Scopes': { main: [[{ node: 'L3 Reasoning', type: 'main', index: 0 }]] },
  'L3 Reasoning': { main: [[{ node: 'Critique & Decide', type: 'main', index: 0 }]] },
  'Critique & Decide': { main: [[{ node: 'Write Result', type: 'main', index: 0 }]] },
};

const workflow = {
  name: 'law-change-digest',
  nodes,
  connections,
  settings: { executionOrder: 'v1' },
};

// ─── Connection-integrity guard (every target node exists) ────────────────────
const nodeNames = new Set(nodes.map((n) => n.name));
const danglers = [];
for (const [from, conn] of Object.entries(connections)) {
  if (!nodeNames.has(from)) danglers.push(`source "${from}" is not a node`);
  for (const out of conn.main || []) {
    for (const c of out || []) {
      if (!nodeNames.has(c.node)) danglers.push(`"${from}" → "${c.node}" (target missing)`);
    }
  }
}
if (danglers.length) {
  console.error('❌ Connection integrity failed:\n  ' + danglers.join('\n  '));
  process.exit(1);
}

const json = JSON.stringify(workflow, null, 2) + '\n';

if (checkOnly) {
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
  if (current !== json) {
    console.error('❌ law-change-digest.json is stale. Run: node scripts/build-law-change-digest.mjs');
    process.exit(1);
  }
  console.log('✅ law-change-digest.json is in sync with its sources.');
  process.exit(0);
}

writeFileSync(outPath, json, 'utf8');
console.log(`✅ Wrote ${outPath}`);
console.log(`   ${nodes.length} nodes, ${Object.keys(connections).length} connection sources, integrity OK.`);
console.log('   Next: node scripts/deploy-workflow.mjs law-change-digest --create   (first time → prints new workflow id)');
