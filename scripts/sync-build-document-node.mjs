/**
 * sync-build-document-node.mjs — regenerate the "Build Document" Code node in
 * n8n/workflows/current/form-submit.json from its tested mirrors (doc-engine, #34).
 *
 * Anti-drift: the node's jsCode is GENERATED from single sources of truth —
 *   n8n/templates/render-document.js          (shared engine, unit-tested)
 *   n8n/templates/divorce-document.js         (legacy js builder)
 *   n8n/templates/alimony-document.js         (legacy js builder)
 * plus the dispatch header/footer defined here. Never edit the node inline;
 * edit a mirror, run this script, then deploy via scripts/deploy-workflow.mjs.
 *
 * Usage:
 *   node scripts/sync-build-document-node.mjs [--check]
 *     --check   exit 1 if the workflow file is out of sync (no write)
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..');
const wfPath = resolve(repoRoot, 'n8n/workflows/current/form-submit.json');
const checkOnly = process.argv.includes('--check');

const read = (p) => readFileSync(resolve(repoRoot, p), 'utf8').replace(/\r\n/g, '\n');

const HEADER = `// ═══════════════════════════════════════════════════════
// Build Document — GENERATED by scripts/sync-build-document-node.mjs
// Do NOT edit inline: edit the mirrors in n8n/templates/ and re-run the script.
// ═══════════════════════════════════════════════════════

// 1. Parse AI declension
let ai = {};
try {
  const raw = $('AI Declension').item.json?.choices?.[0]?.message?.content || '{}';
  const cleaned = raw.replace(/\`\`\`json?\\n?/g, '').replace(/\`/g, '').trim();
  ai = JSON.parse(cleaned);
  console.log('[Build] AI parsed OK:', Object.keys(ai).join(', '));
} catch (e) {
  console.log('[Build] AI parse failed, using fallbacks:', e.message);
}

// 2. Service data
const serviceSlug = $('Validate').item.json._service_slug || 'divorce';
const answers = $('Validate').item.json._answers || {};
const caseId = $('Insert Case').item.json.id;
const svc = $('Get Service').first().json || {};
`;

const FOOTER = `
// 5. Dispatch by generation_mode (doc-engine, #34; hybrid added #37; style hints #50)
// 'hybrid'   → template engine + AI reasoning; returns _style_hints for typography
// 'template' → shared render engine; returns _style_hints for typography
// anything else → legacy hardcoded js builder (no style hints)
let document;
let styleHints = {};
let reviewCard = null;
let abstained = null; // null = non-hybrid; true/false = hybrid result (#73)
try {
  if (svc.generation_mode === 'hybrid' && svc.document_template) {
    console.log('[Build] path=hybrid, service', serviceSlug);
    const hybridCtx = $json || {};
    if (hybridCtx._ai_reasoning) { ai.reasoning = hybridCtx._ai_reasoning; }
    reviewCard = hybridCtx._review_card || null;
    abstained = hybridCtx._abstained === true ? true : false;
    const rendered = renderDocumentWithStyles(svc.document_template, buildContext(answers, ai));
    document = rendered.text;
    styleHints = rendered.styleHints;
  } else if (svc.generation_mode === 'template' && svc.document_template) {
    console.log('[Build] path=template (engine), service', serviceSlug);
    const rendered = renderDocumentWithStyles(svc.document_template, buildContext(answers, ai));
    document = rendered.text;
    styleHints = rendered.styleHints;
  } else {
    console.log('[Build] path=js (legacy builder), service', serviceSlug);
    const builders = { divorce: buildDivorceDocument, alimony: buildAlimonyDocument };
    const builder = builders[serviceSlug];
    if (!builder) {
      throw new Error('No js builder for service "' + serviceSlug +
        '" and no usable template (generation_mode=' + (svc.generation_mode || 'js') + ')');
    }
    document = builder(answers, ai);
  }
} catch (e) {
  throw new Error('Document generation failed for ' + serviceSlug + ' (case ' + caseId + '): ' + e.message);
}
console.log('[Build] Generated', document.length, 'chars,', Object.keys(styleHints).length, 'styled paragraphs for', serviceSlug);

return [{ json: { _content: document, _case_id: caseId, _review_card: reviewCard, _style_hints: styleHints, _abstained: abstained } }];
`;

const jsCode = [
  HEADER,
  '// 3. Shared render engine (mirror: n8n/templates/render-document.js)',
  read('n8n/templates/render-document.js'),
  '// 4a. Legacy builder (mirror: n8n/templates/divorce-document.js)',
  read('n8n/templates/divorce-document.js'),
  '// 4b. Legacy builder (mirror: n8n/templates/alimony-document.js)',
  read('n8n/templates/alimony-document.js'),
  FOOTER,
].join('\n');

const wfRaw = readFileSync(wfPath, 'utf8');
const wf = JSON.parse(wfRaw);
const node = wf.nodes.find((n) => n.name === 'Build Document');
if (!node) {
  console.error('Build Document node not found in form-submit.json');
  process.exit(1);
}

if (node.parameters.jsCode === jsCode) {
  console.log('✅ Build Document node already in sync (' + jsCode.length + ' chars).');
  process.exit(0);
}

if (checkOnly) {
  console.error('❌ Build Document node is OUT OF SYNC with its mirrors. Run: node scripts/sync-build-document-node.mjs');
  process.exit(1);
}

const before = node.parameters.jsCode.length;
node.parameters.jsCode = jsCode;
writeFileSync(wfPath, JSON.stringify(wf, null, 2) + '\n', 'utf8');
console.log(`✅ Build Document node regenerated: ${before} → ${jsCode.length} chars.`);
console.log('Next: node scripts/deploy-workflow.mjs form-submit');
