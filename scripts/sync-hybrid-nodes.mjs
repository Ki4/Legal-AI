/**
 * sync-hybrid-nodes.mjs — patch form-submit.json with the L2→L3→L4 hybrid pipeline.
 *
 * Anti-drift: Code node jsCode is GENERATED from single sources of truth:
 *   n8n/templates/prepare-reasoning.js
 *   n8n/templates/build-hybrid-context.js
 *   n8n/templates/groundedness.js
 *   n8n/prompts/alimony-change-reasoning.txt
 *
 * What this script does (idempotent):
 *   1. Shifts Build Document + downstream main-line nodes right by 1200.
 *   2. Inserts 6 new nodes: Is Hybrid?, Skip Hybrid, L2 Get Norms,
 *      Prepare Reasoning, L3 Reasoning, L4 Critics.
 *   3. Rewires connections:
 *        REMOVE  AI Declension → Build Document
 *        ADD     AI Declension → Is Hybrid?
 *        ADD     Is Hybrid? true(0) → L2 Get Norms
 *        ADD     Is Hybrid? false(1) → Skip Hybrid
 *        ADD     L2 Get Norms → Prepare Reasoning → L3 Reasoning → L4 Critics
 *        ADD     L4 Critics → Build Document
 *        ADD     Skip Hybrid → Build Document
 *
 * Usage:
 *   node scripts/sync-hybrid-nodes.mjs [--check]
 *     --check   exit 1 if hybrid nodes are missing (CI guard); exit 0 if in sync
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot  = resolve(__dirname, '..');
const wfPath    = resolve(repoRoot, 'n8n/workflows/current/form-submit.json');
const checkOnly = process.argv.includes('--check');

const read = (p) => readFileSync(resolve(repoRoot, p), 'utf8').replace(/\r\n/g, '\n');

// ─── Generated Code node bodies ───────────────────────────────────────────────

const SKIP_HYBRID_CODE = [
  '// Skip Hybrid — non-hybrid services bypass the L2→L3→L4 pipeline.',
  "return [{ json: { _ai_reasoning: '', _review_card: null, _spans: [], _has_red: false, _abstained: false } }];",
].join('\n');

const PREPARE_REASONING_CODE = [
  '// ═══════════════════════════════════════════════════════',
  '// Prepare Reasoning — GENERATED by scripts/sync-hybrid-nodes.mjs',
  '// Edit n8n/templates/prepare-reasoning.js and re-run this script.',
  '// ═══════════════════════════════════════════════════════',
  '',
  '// Prompt template (mirror: n8n/prompts/alimony-change-reasoning.txt)',
  'const REASONING_PROMPT_TEMPLATE = ' + JSON.stringify(read('n8n/prompts/alimony-change-reasoning.txt')) + ';',
  '',
  '// Core function (mirror: n8n/templates/prepare-reasoning.js)',
  read('n8n/templates/prepare-reasoning.js'),
  '',
  '// n8n entry point:',
  "const answers = $('Validate').item.json._answers || {};",
  "const l2Rows = $('L2 Get Norms').all().map(item => item.json);",
  "const modelName = $('Global Config').first().json.GROQ_MODEL || 'llama-3.3-70b-versatile';",
  'const result = prepareReasoning(answers, l2Rows, REASONING_PROMPT_TEMPLATE, modelName);',
  'return [{ json: result }];',
].join('\n');

const L4_CRITICS_CODE = [
  '// ═══════════════════════════════════════════════════════',
  '// L4 Critics — GENERATED by scripts/sync-hybrid-nodes.mjs',
  '// Edit n8n/templates/build-hybrid-context.js and re-run this script.',
  '// ═══════════════════════════════════════════════════════',
  '',
  '// L4a critic (mirror: n8n/templates/groundedness.js)',
  read('n8n/templates/groundedness.js'),
  '',
  '// L4 context builder (mirror: n8n/templates/build-hybrid-context.js)',
  read('n8n/templates/build-hybrid-context.js'),
  '',
  '// n8n entry point:',
  'const l3Response = $json;',
  "const prepCtx = $('Prepare Reasoning').first().json;",
  'const l2ArticleIds = prepCtx._l2_article_ids || [];',
  'const answers = prepCtx._answers_snapshot || {};',
  'const result = buildHybridContext(l3Response, l2ArticleIds, answers, checkGroundedness);',
  'return [{ json: result }];',
].join('\n');

// ─── Node definitions ─────────────────────────────────────────────────────────
// n8n expression for full Supabase URL. Curly braces inside the PostgreSQL cs.{}
// operator must be literal — they are inside a JSON string, not an n8n expression,
// so they do NOT need escaping. The leading ={{ ... }} makes the whole field an expression.
const SUPABASE_URL_EXPR = "={{ $('Global Config').first().json.SUPABASE_URL + '/rest/v1/law_chunks?service_slugs=cs.{alimony-change}&select=law_code,article_num,article_title,content&order=article_num.asc' }}"
const SUPABASE_KEY_EXPR = "={{ $('Global Config').first().json.SUPABASE_SERVICE_KEY }}"
const SUPABASE_AUTH_EXPR = "={{ 'Bearer ' + $('Global Config').first().json.SUPABASE_SERVICE_KEY }}"

const NEW_NODES = [
  {
    id:          'is-hybrid-001',
    name:        'Is Hybrid?',
    type:        'n8n-nodes-base.if',
    typeVersion: 1,
    position:    [1120, 1580],
    parameters: {
      conditions: {
        string: [{
          value1:    "={{ $('Get Service').first().json.generation_mode }}",
          operation: 'equal',
          value2:    'hybrid',
        }],
      },
    },
  },
  {
    id:          'skip-hybrid-001',
    name:        'Skip Hybrid',
    type:        'n8n-nodes-base.code',
    typeVersion: 2,
    position:    [1120, 1340],
    parameters:  { jsCode: SKIP_HYBRID_CODE },
  },
  {
    id:          'l2-get-norms-001',
    name:        'L2 Get Norms',
    type:        'n8n-nodes-base.httpRequest',
    typeVersion: 4.2,
    position:    [1360, 1820],
    parameters: {
      method:      'GET',
      url:         SUPABASE_URL_EXPR,
      sendHeaders: true,
      headerParameters: {
        parameters: [
          { name: 'apikey',        value: SUPABASE_KEY_EXPR },
          { name: 'Authorization', value: SUPABASE_AUTH_EXPR },
        ],
      },
      options: { timeout: 15000 },
    },
  },
  {
    id:          'prepare-reasoning-001',
    name:        'Prepare Reasoning',
    type:        'n8n-nodes-base.code',
    typeVersion: 2,
    position:    [1600, 1820],
    parameters:  { jsCode: PREPARE_REASONING_CODE },
  },
  {
    id:          'l3-reasoning-001',
    name:        'L3 Reasoning',
    type:        'n8n-nodes-base.httpRequest',
    typeVersion: 4.2,
    position:    [1840, 1820],
    parameters: {
      method:          'POST',
      url:             'https://api.groq.com/openai/v1/chat/completions',
      authentication:  'genericCredentialType',
      genericAuthType: 'httpHeaderAuth',
      sendHeaders:     true,
      headerParameters: {
        parameters: [{ name: 'Content-Type', value: 'application/json' }],
      },
      sendBody:    true,
      specifyBody: 'json',
      jsonBody:    '={{ JSON.stringify($json._groq_body) }}',
      options:     { timeout: 60000 },
    },
    credentials: {
      httpHeaderAuth: { id: 'groq-http-auth', name: 'Groq HTTP Auth' },
    },
  },
  {
    id:          'l4-critics-001',
    name:        'L4 Critics',
    type:        'n8n-nodes-base.code',
    typeVersion: 2,
    position:    [2080, 1820],
    parameters:  { jsCode: L4_CRITICS_CODE },
  },
];

// Main-pipeline nodes (y=1580) that sit at x >= 1120 — shift these right.
const SHIFT_NODES = new Set([
  'Build Document', 'Notify User', 'Respond OK',
  'Copy Template', 'Build Replace Request', 'Replace Placeholder',
  'Share Document', 'Send Doc Link',
]);

const SHIFT_X = 1200;

// ─── Connection tables ────────────────────────────────────────────────────────

function buildHybridConnections() {
  return {
    'AI Declension':    { main: [[{ node: 'Is Hybrid?',        type: 'main', index: 0 }]] },
    'Is Hybrid?':       { main: [
      [{ node: 'L2 Get Norms',    type: 'main', index: 0 }],   // output 0 = true
      [{ node: 'Skip Hybrid',     type: 'main', index: 0 }],   // output 1 = false
    ]},
    'L2 Get Norms':     { main: [[{ node: 'Prepare Reasoning', type: 'main', index: 0 }]] },
    'Prepare Reasoning':{ main: [[{ node: 'L3 Reasoning',      type: 'main', index: 0 }]] },
    'L3 Reasoning':     { main: [[{ node: 'L4 Critics',        type: 'main', index: 0 }]] },
    // Both L4 Critics and Skip Hybrid feed Build Document.
    // IF sends to exactly ONE branch per execution, so no Merge node is needed.
    'L4 Critics':       { main: [[{ node: 'Build Document',    type: 'main', index: 0 }]] },
    'Skip Hybrid':      { main: [[{ node: 'Build Document',    type: 'main', index: 0 }]] },
  }
}

// ─── Main ─────────────────────────────────────────────────────────────────────

const wfRaw = readFileSync(wfPath, 'utf8');
const wf    = JSON.parse(wfRaw);

// Idempotency — check if hybrid pipeline already present.
const alreadyPatched = wf.nodes.some(n => n.name === 'Is Hybrid?');

if (alreadyPatched) {
  if (checkOnly) {
    console.log('✅ Hybrid nodes already present — workflow is in sync.');
    process.exit(0);
  }

  // Re-run: refresh only the generated Code node jsCode when templates have changed.
  const codeMap = {
    'Skip Hybrid':       SKIP_HYBRID_CODE,
    'Prepare Reasoning': PREPARE_REASONING_CODE,
    'L4 Critics':        L4_CRITICS_CODE,
  };
  let changed = false;
  for (const node of wf.nodes) {
    const fresh = codeMap[node.name];
    if (fresh && node.parameters?.jsCode !== fresh) {
      console.log(`  ↻ Refreshing "${node.name}" (${node.parameters.jsCode.length} → ${fresh.length} chars)`);
      node.parameters.jsCode = fresh;
      changed = true;
    }
  }
  if (!changed) {
    console.log('✅ All hybrid Code nodes already in sync.');
    process.exit(0);
  }
  writeFileSync(wfPath, JSON.stringify(wf, null, 2) + '\n', 'utf8');
  console.log('✅ Hybrid Code nodes refreshed. Next: node scripts/deploy-workflow.mjs form-submit');
  process.exit(0);
}

if (checkOnly) {
  console.error('❌ Hybrid nodes NOT in form-submit.json. Run: node scripts/sync-hybrid-nodes.mjs');
  process.exit(1);
}

// 1. Shift downstream main-pipeline nodes to the right.
for (const node of wf.nodes) {
  if (SHIFT_NODES.has(node.name)) {
    node.position = [node.position[0] + SHIFT_X, node.position[1]];
  }
}

// 2. Add the 6 new hybrid nodes.
wf.nodes.push(...NEW_NODES);

// 3. Rewire connections.
//    Delete the AI Declension → Build Document edge (replaced by AI Declension → Is Hybrid?).
delete wf.connections['AI Declension'];
Object.assign(wf.connections, buildHybridConnections());

// 4. Write back.
writeFileSync(wfPath, JSON.stringify(wf, null, 2) + '\n', 'utf8');

console.log('✅ Hybrid pipeline patched into form-submit.json:');
console.log('   +6 nodes: Is Hybrid?, Skip Hybrid, L2 Get Norms, Prepare Reasoning, L3 Reasoning, L4 Critics');
console.log(`   Shifted ${SHIFT_NODES.size} downstream nodes +${SHIFT_X}px.`);
console.log('');
console.log('Next steps:');
console.log('  1. node scripts/sync-build-document-node.mjs  (add hybrid dispatch)');
console.log('  2. node scripts/deploy-workflow.mjs form-submit');
