/**
 * sync-l4b-nodes.mjs — patch form-submit.json with the L4b LLM Critic step.
 *
 * Anti-drift: Code node jsCode is GENERATED from single sources of truth:
 *   n8n/templates/prepare-l4b.js
 *   n8n/prompts/alimony-change-critic.txt
 *
 * What this script does (idempotent):
 *   Prerequisite: form-submit.json already has the base hybrid pipeline
 *                 (L3 Reasoning → L4 Critics) from sync-hybrid-nodes.mjs.
 *
 *   1. Shifts L4 Critics right by 480px (to [2560, 1820]).
 *   2. Shifts Build Document right by 480px.
 *   3. Inserts 2 new nodes: Prepare L4b [2080, 1820], L4b LLM Critic [2320, 1820].
 *   4. Rewires: L3 Reasoning → Prepare L4b → L4b LLM Critic → L4 Critics.
 *   5. Updates L4 Critics jsCode entry point to read both L3 and L4b results.
 *
 * Usage:
 *   node scripts/sync-l4b-nodes.mjs [--check]
 *     --check   exit 1 if L4b nodes are missing; exit 0 if in sync
 *
 * Run order (after this, deploy):
 *   node scripts/sync-hybrid-nodes.mjs
 *   node scripts/sync-l4b-nodes.mjs          ← this script
 *   node scripts/sync-build-document-node.mjs
 *   node scripts/sync-typography-nodes.mjs
 *   node scripts/deploy-workflow.mjs form-submit
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot  = resolve(__dirname, '..');
const wfPath    = resolve(repoRoot, 'n8n/workflows/current/form-submit.json');
const checkOnly = process.argv.includes('--check');

const read = (p) => readFileSync(resolve(repoRoot, p), 'utf8').replace(/\r\n/g, '\n');

// ─── Generated Code node bodies ───────────────────────────────────────────────

const PREPARE_L4B_CODE = [
  '// ═══════════════════════════════════════════════════════',
  '// Prepare L4b — GENERATED by scripts/sync-l4b-nodes.mjs',
  '// Edit n8n/templates/prepare-l4b.js and re-run this script.',
  '// ═══════════════════════════════════════════════════════',
  '',
  '// Critic prompt template (mirror: n8n/prompts/alimony-change-critic.txt)',
  'const L4B_PROMPT_TEMPLATE = ' + JSON.stringify(read('n8n/prompts/alimony-change-critic.txt')) + ';',
  '',
  '// Core function (mirror: n8n/templates/prepare-l4b.js)',
  read('n8n/templates/prepare-l4b.js'),
  '',
  '// n8n entry point:',
  'const l3Response = $json;',
  'let reasoningText = \'\';',
  'try {',
  '  const raw = l3Response?.choices?.[0]?.message?.content || \'\';',
  '  const cleaned = raw.replace(/```json?\\n?/g, \'\').replace(/```/g, \'\').trim();',
  '  const l3Parsed = JSON.parse(cleaned);',
  '  reasoningText = l3Parsed.reasoning_text || \'\';',
  '} catch (_) { /* parse failed — empty string → trivially GREEN L4b */ }',
  '',
  "const prepCtx = $('Prepare Reasoning').first().json;",
  'const answers = prepCtx._answers_snapshot || {};',
  'const l2NormsText = prepCtx._l2_norms_text || \'\';',
  "const direction = answers.change_direction === 'increase' ? 'Збільшення' : 'Зменшення';",
  'const changedFacts = Array.isArray(answers.changed_facts) ? answers.changed_facts : [];',
  "const modelName = $('Global Config').first().json.GROQ_MODEL || 'llama-3.3-70b-versatile';",
  '',
  'const result = prepareL4b(reasoningText, direction, changedFacts, l2NormsText, L4B_PROMPT_TEMPLATE, modelName);',
  'return [{ json: result }];',
].join('\n');

// Updated L4 Critics entry point — reads L3 by name (since L4b is now the direct predecessor)
const L4_CRITICS_CODE_WITH_L4B = [
  '// ═══════════════════════════════════════════════════════',
  '// L4 Critics — GENERATED by scripts/sync-l4b-nodes.mjs',
  '// Edit n8n/templates/build-hybrid-context.js and re-run this script.',
  '// ═══════════════════════════════════════════════════════',
  '',
  '// L4a critic (mirror: n8n/templates/groundedness.js)',
  read('n8n/templates/groundedness.js'),
  '',
  '// L4 context builder (mirror: n8n/templates/build-hybrid-context.js)',
  read('n8n/templates/build-hybrid-context.js'),
  '',
  '// n8n entry point (L4b LLM Critic is now the direct predecessor):',
  "const l3Response = $('L3 Reasoning').first().json;",
  'const l4bRaw = $json;',
  "const prepCtx = $('Prepare Reasoning').first().json;",
  'const l2ArticleIds = prepCtx._l2_article_ids || [];',
  'const answers = prepCtx._answers_snapshot || {};',
  'const result = buildHybridContext(l3Response, l2ArticleIds, answers, checkGroundedness, l4bRaw);',
  'return [{ json: result }];',
].join('\n');

// ─── Node definitions ─────────────────────────────────────────────────────────

const GROQ_URL   = 'https://api.groq.com/openai/v1/chat/completions';
const GROQ_CREDS = { httpHeaderAuth: { id: 'groq-http-auth', name: 'Groq HTTP Auth' } };

const NEW_NODES = [
  {
    id:          'prepare-l4b-001',
    name:        'Prepare L4b',
    type:        'n8n-nodes-base.code',
    typeVersion: 2,
    position:    [2080, 1820],
    parameters:  { jsCode: PREPARE_L4B_CODE },
  },
  {
    id:          'l4b-llm-critic-001',
    name:        'L4b LLM Critic',
    type:        'n8n-nodes-base.httpRequest',
    typeVersion: 4.2,
    position:    [2320, 1820],
    parameters: {
      method:          'POST',
      url:             GROQ_URL,
      authentication:  'genericCredentialType',
      genericAuthType: 'httpHeaderAuth',
      sendHeaders:     true,
      headerParameters: {
        parameters: [{ name: 'Content-Type', value: 'application/json' }],
      },
      sendBody:    true,
      specifyBody: 'json',
      jsonBody:    '={{ JSON.stringify($json._groq_body) }}',
      options:     { timeout: 60000 },
    },
    credentials: GROQ_CREDS,
  },
];

// ─── Main ─────────────────────────────────────────────────────────────────────

const wfRaw = readFileSync(wfPath, 'utf8');
const wf    = JSON.parse(wfRaw);

// Guard: base hybrid pipeline must already be present.
if (!wf.nodes.some(n => n.name === 'L3 Reasoning')) {
  console.error('❌ Base hybrid pipeline not found. Run sync-hybrid-nodes.mjs first.');
  process.exit(1);
}

// Idempotency — check if L4b already present.
const alreadyPatched = wf.nodes.some(n => n.name === 'L4b LLM Critic');

if (alreadyPatched) {
  if (checkOnly) {
    console.log('✅ L4b nodes already present — workflow is in sync.');
    process.exit(0);
  }

  // Re-run: refresh jsCode in generated Code nodes when source files change.
  const codeMap = {
    'Prepare L4b': PREPARE_L4B_CODE,
    'L4 Critics':  L4_CRITICS_CODE_WITH_L4B,
  };
  let changed = false;
  for (const node of wf.nodes) {
    const fresh = codeMap[node.name];
    if (fresh && node.parameters?.jsCode !== fresh) {
      console.log(`  ↻ Refreshing "${node.name}" (${node.parameters.jsCode.length} → ${fresh.length} chars)`);
      node.parameters.jsCode = fresh;
      changed = true;
    }
  }
  if (!changed) {
    console.log('✅ All L4b Code nodes already in sync.');
    process.exit(0);
  }
  writeFileSync(wfPath, JSON.stringify(wf, null, 2) + '\n', 'utf8');
  console.log('✅ L4b Code nodes refreshed. Next: node scripts/deploy-workflow.mjs form-submit');
  process.exit(0);
}

if (checkOnly) {
  console.error('❌ L4b nodes NOT in form-submit.json. Run: node scripts/sync-l4b-nodes.mjs');
  process.exit(1);
}

// 1. Shift L4 Critics right by +480.
const l4CriticsNode = wf.nodes.find(n => n.name === 'L4 Critics');
if (l4CriticsNode) l4CriticsNode.position[0] += 480;

// 2. Shift Build Document right by +480 (visual alignment).
const buildDocNode = wf.nodes.find(n => n.name === 'Build Document');
if (buildDocNode) buildDocNode.position[0] += 480;

// 3. Add the 2 new L4b nodes.
wf.nodes.push(...NEW_NODES);

// 4. Update L4 Critics jsCode to use the L4b-aware entry point.
if (l4CriticsNode) l4CriticsNode.parameters.jsCode = L4_CRITICS_CODE_WITH_L4B;

// 5. Rewire connections:
//    L3 Reasoning → L4 Critics  becomes  L3 Reasoning → Prepare L4b → L4b LLM Critic → L4 Critics
delete wf.connections['L3 Reasoning'];
Object.assign(wf.connections, {
  'L3 Reasoning':   { main: [[{ node: 'Prepare L4b',     type: 'main', index: 0 }]] },
  'Prepare L4b':    { main: [[{ node: 'L4b LLM Critic',  type: 'main', index: 0 }]] },
  'L4b LLM Critic': { main: [[{ node: 'L4 Critics',      type: 'main', index: 0 }]] },
});

// 6. Write back.
writeFileSync(wfPath, JSON.stringify(wf, null, 2) + '\n', 'utf8');

console.log('✅ L4b pipeline patched into form-submit.json:');
console.log('   +2 nodes: Prepare L4b, L4b LLM Critic');
console.log('   L4 Critics entry point updated to read L4b result.');
console.log('');
console.log('Next steps:');
console.log('  node scripts/deploy-workflow.mjs form-submit');
