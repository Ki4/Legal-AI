// sync-preview-module-form-submit.mjs — idempotent patcher for form-submit.json
//
// preview-module G3 CORE (#83, p1+2 — rate-limit is a separate pass, G3b):
//
//  p1 — safe excerpt rides the EARLY webhook response:
//    Build Document already emits the full text in `_content` and responds early
//    (Respond OK fires right after Build Document, before the slow PDF tail, to
//    dodge a ~40-60s webhook timeout). We insert a `Derive Excerpt` node that runs
//    the SSoT extractor (n8n/templates/preview-excerpt.js, inlined below) over
//    `_content`, then:
//      • Update Case Abstention also writes preview_excerpt + status='generating'
//      • Respond OK returns { success, case_id, status, preview_excerpt }
//      • Insert Case default status 'submitted' → 'generating'
//
//  p2 — the async tail STOPS delivering the doc to the bot before payment and
//    instead parks the full PDF in the PRIVATE `generated-documents` bucket:
//      Export PDF → Upload PDF to Storage → Set Preview Ready → Delete Doc
//    (Send PDF / Export DOCX / Send DOCX removed. PDF-only this iteration — the
//     bucket allows only application/pdf; DOCX-after-pay is deferred, IMPROVEMENTS.)
//    The signed URL is minted later, server-side, by preview-pay (G4) — never here.
//
// Secrets stay out of the committed JSON: the upload reads SUPABASE_URL /
// SUPABASE_SERVICE_KEY from the Global Config node (deploy-workflow injects the
// real values at deploy time, like every other node).
//
// Run, then:
//   node scripts/deploy-workflow.mjs form-submit --check
//   node scripts/deploy-workflow.mjs form-submit
//
// Idempotent: re-running converges to the same graph.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const WF_FILE = resolve(ROOT, 'n8n/workflows/current/form-submit.json');
const EXCERPT_SRC = resolve(ROOT, 'n8n/templates/preview-excerpt.js');

const SUPABASE_CRED = { id: '2hBYjVwFlJbTj7AK', name: 'Supabase account' };
const BUCKET = 'generated-documents';

// G3b rate-limit (#83): max preview cases a single profile may create per 24h.
// Env-overridable so a smoke can force the over-limit path; committed default = prod.
const PREVIEW_RATE_LIMIT = Number(process.env.PREVIEW_RATE_LIMIT) || 20;

const wf = JSON.parse(readFileSync(WF_FILE, 'utf8'));
const getNode = (name) => wf.nodes.find((n) => n.name === name);
let changed = 0;

// ── Inline the SSoT excerpt extractor (strip the module.exports tail) ──────────
const excerptSource = readFileSync(EXCERPT_SRC, 'utf8')
  .replace(/\/\/ ── Exports[\s\S]*$/m, '')
  .trim();

// ── p1.1 — Derive Excerpt code node ───────────────────────────────────────────
const deriveCode = `// Derive Excerpt — GENERATED by scripts/sync-preview-module-form-submit.mjs
// SSoT: n8n/templates/preview-excerpt.js (inlined; edit there + re-run, never here).
${excerptSource}

// Safe preview excerpt from the rendered document text (Build Document._content).
const bd = $('Build Document').item.json;
const serviceSlug = $('Validate').item.json._service_slug || 'divorce';
const _preview_excerpt = deriveExcerpt(bd._content, serviceSlug);
console.log('[Excerpt] derived', _preview_excerpt.length, 'chars for', serviceSlug);
return [{ json: { ...bd, _preview_excerpt } }];
`;

(function upsertDeriveExcerpt() {
  let node = getNode('Derive Excerpt');
  if (!node) {
    node = {
      id: 'derive-excerpt-001',
      name: 'Derive Excerpt',
      type: 'n8n-nodes-base.code',
      typeVersion: 2,
      position: [2680, 1700],
      parameters: {},
    };
    wf.nodes.push(node);
    console.log('✓ added "Derive Excerpt"');
    changed++;
  }
  if (node.parameters.jsCode !== deriveCode) {
    node.parameters.jsCode = deriveCode;
    console.log('✓ synced "Derive Excerpt" jsCode');
    changed++;
  }
})();

// Rewire: Build Document → Derive Excerpt → [Notify User, Update Case Abstention]
wf.connections['Build Document'] = { main: [[{ node: 'Derive Excerpt', type: 'main', index: 0 }]] };
wf.connections['Derive Excerpt'] = {
  main: [[
    { node: 'Notify User', type: 'main', index: 0 },
    { node: 'Update Case Abstention', type: 'main', index: 0 },
  ]],
};

// ── p1.2 — Update Case Abstention: also persist preview_excerpt ────────────────
// IMPORTANT: do NOT write `status` here. n8n runs depth-first, so the Notify-User
// branch (… → Set Preview Ready, which flips status→'preview_ready') completes
// BEFORE this sibling node runs — writing status='generating' here would clobber
// 'preview_ready' back. Status is owned solely by Insert Case ('generating') and
// Set Preview Ready ('preview_ready'); this node only adds the excerpt.
(function patchUpdateCase() {
  const node = getNode('Update Case Abstention');
  const fv = node.parameters.fieldsUi.fieldValues;
  // Drop any previously-synced status field (the clobber bug).
  const before = fv.length;
  node.parameters.fieldsUi.fieldValues = fv.filter((f) => f.fieldId !== 'status');
  if (node.parameters.fieldsUi.fieldValues.length !== before) { changed++; console.log('✓ Update Case Abstention -status (avoid clobber)'); }
  const fv2 = node.parameters.fieldsUi.fieldValues;
  if (!fv2.find((f) => f.fieldId === 'preview_excerpt')) {
    fv2.push({ fieldId: 'preview_excerpt', fieldValue: '={{ $json._preview_excerpt }}' });
    changed++; console.log('✓ Update Case Abstention +preview_excerpt');
  }
})();

// ── p1.3 — Respond OK returns case_id + status + preview_excerpt ───────────────
(function patchRespondOK() {
  const node = getNode('Respond OK');
  const body = "={{ JSON.stringify({ success: true, case_id: $('Insert Case').item.json.id, status: 'generating', preview_excerpt: $('Derive Excerpt').item.json._preview_excerpt }) }}";
  if (node.parameters.responseBody !== body) {
    node.parameters.responseBody = body;
    console.log('✓ synced "Respond OK" responseBody');
    changed++;
  }
})();

// ── p1.4 — Insert Case default status 'submitted' → 'generating' ───────────────
(function patchInsertCase() {
  const fv = getNode('Insert Case').parameters.fieldsUi.fieldValues;
  const st = fv.find((f) => f.fieldId === 'status');
  if (st && st.fieldValue !== 'generating') { st.fieldValue = 'generating'; changed++; console.log('✓ Insert Case status → generating'); }
})();

// ── p2.1 — Upload PDF to private Storage (binary body, service-role) ───────────
const STORAGE_URL = "=" + "{{ $('Global Config').first().json.SUPABASE_URL }}/storage/v1/object/" + BUCKET + "/cases/{{ $('Insert Case').item.json.id }}.pdf";
const SERVICE_KEY_EXPR = "{{ $('Global Config').first().json.SUPABASE_SERVICE_KEY }}";
(function upsertUpload() {
  let node = getNode('Upload PDF to Storage');
  const parameters = {
    method: 'POST',
    url: STORAGE_URL,
    sendHeaders: true,
    headerParameters: {
      parameters: [
        { name: 'Authorization', value: '=Bearer ' + SERVICE_KEY_EXPR },
        { name: 'apikey', value: '=' + SERVICE_KEY_EXPR },
        { name: 'Content-Type', value: 'application/pdf' },
        { name: 'x-upsert', value: 'true' },
      ],
    },
    sendBody: true,
    contentType: 'binaryData',
    inputDataFieldName: 'data',
    options: {},
  };
  if (!node) {
    node = {
      id: 'upload-pdf-storage-001',
      name: 'Upload PDF to Storage',
      type: 'n8n-nodes-base.httpRequest',
      typeVersion: 4.2,
      position: [4720, 1580],
      parameters,
      onError: 'continueErrorOutput',
    };
    wf.nodes.push(node);
    console.log('✓ added "Upload PDF to Storage"');
    changed++;
  } else {
    node.parameters = parameters;
    node.onError = 'continueErrorOutput';
  }
})();

// ── p2.2 — Set Preview Ready (doc_storage_path + status='preview_ready') ───────
(function upsertSetReady() {
  let node = getNode('Set Preview Ready');
  const parameters = {
    operation: 'update',
    tableId: 'cases',
    filters: { conditions: [{ keyName: 'id', condition: 'eq', keyValue: "={{ $('Insert Case').item.json.id }}" }] },
    fieldsUi: {
      fieldValues: [
        { fieldId: 'doc_storage_path', fieldValue: "=cases/{{ $('Insert Case').item.json.id }}.pdf" },
        { fieldId: 'status', fieldValue: 'preview_ready' },
      ],
    },
  };
  if (!node) {
    node = {
      id: 'set-preview-ready-001',
      name: 'Set Preview Ready',
      type: 'n8n-nodes-base.supabase',
      typeVersion: 1,
      position: [4960, 1580],
      parameters,
      credentials: { supabaseApi: SUPABASE_CRED },
      // Don't let a status-write hiccup block Delete Doc (PII cleanup of the Google Doc).
      onError: 'continueRegularOutput',
    };
    wf.nodes.push(node);
    console.log('✓ added "Set Preview Ready"');
    changed++;
  } else {
    node.parameters = parameters;
    node.credentials = { supabaseApi: SUPABASE_CRED };
    node.onError = 'continueRegularOutput';
  }
})();

// ── p2.3 — Rewire the tail; drop pre-payment bot delivery ──────────────────────
// Export PDF: success → Upload (keep error output → Format Gen Failure).
wf.connections['Export PDF'] = {
  main: [
    [{ node: 'Upload PDF to Storage', type: 'main', index: 0 }],
    [{ node: 'Format Gen Failure', type: 'main', index: 0 }],
  ],
};
wf.connections['Upload PDF to Storage'] = {
  main: [
    [{ node: 'Set Preview Ready', type: 'main', index: 0 }],
    [{ node: 'Format Gen Failure', type: 'main', index: 0 }],
  ],
};
wf.connections['Set Preview Ready'] = {
  main: [[{ node: 'Delete Doc', type: 'main', index: 0 }]],
};

// Remove the bot-delivery nodes + any dangling connections out of them.
const REMOVE = ['Send PDF', 'Export DOCX', 'Send DOCX'];
for (const name of REMOVE) {
  const before = wf.nodes.length;
  wf.nodes = wf.nodes.filter((n) => n.name !== name);
  if (wf.nodes.length !== before) { console.log(`✓ removed "${name}"`); changed++; }
  delete wf.connections[name];
}

// ── G3b — per-profile rate limit (anti-abuse) ─────────────────────────────────
// Gate the Has Profile?=true branch: count this profile's cases in the last 24h
// (cases.user_id = profile UUID from Get Profile; migration 029 added the
// (user_id, created_at) index for exactly this). At/over PREVIEW_RATE_LIMIT → 429,
// never inserting a case. Fail-open: a failed count query never blocks a legit user.
const RL_GET_URL =
  "={{ $('Global Config').first().json.SUPABASE_URL + '/rest/v1/cases?user_id=eq.' + " +
  "$('Get Profile').first().json.user_id + '&created_at=gt.' + " +
  "new Date(Date.now() - 86400000).toISOString() + '&select=id&limit=" + (PREVIEW_RATE_LIMIT + 1) + "' }}";

const RL_GATE_CODE = `// Rate Limit Gate — GENERATED by scripts/sync-preview-module-form-submit.mjs
// Counts this profile's cases in the last 24h (from Check Rate Limit) and decides.
const LIMIT = ${PREVIEW_RATE_LIMIT};
const rows = $('Check Rate Limit').all().filter((i) => i && i.json && i.json.id);
const count = rows.length;
// DELIBERATE fail-open (not a security control): the REAL anti-bot gate is the
// fail-CLOSED initData HMAC (#56) upstream — nothing reaches here unsigned. This is a
// secondary per-profile throttle. Fail-open is not exploitable: bypassing it needs the
// count query to fail, but Insert Case (the abuse payload) hits the SAME Supabase, so a
// count failure ⇒ insert also fails ⇒ no document. Fail-closed would instead 429 a
// legit/paying user on a transient DB blip (worse for a quality-first product).
return [{ json: { _rl_count: count, _rl_under: count < LIMIT } }];
`;

(function upsertCheckRateLimit() {
  let node = getNode('Check Rate Limit');
  const parameters = {
    method: 'GET',
    url: RL_GET_URL,
    sendHeaders: true,
    headerParameters: {
      parameters: [
        { name: 'apikey', value: '=' + SERVICE_KEY_EXPR },
        { name: 'Authorization', value: '=Bearer ' + SERVICE_KEY_EXPR },
      ],
    },
    options: { timeout: 15000 },
  };
  if (!node) {
    node = {
      id: 'check-rate-limit-001', name: 'Check Rate Limit',
      type: 'n8n-nodes-base.httpRequest', typeVersion: 4.2, position: [340, 1800],
      parameters, alwaysOutputData: true, onError: 'continueRegularOutput',
    };
    wf.nodes.push(node); console.log('✓ added "Check Rate Limit"'); changed++;
  } else { node.parameters = parameters; node.alwaysOutputData = true; node.onError = 'continueRegularOutput'; }
})();

(function upsertRateLimitGate() {
  let node = getNode('Rate Limit Gate');
  if (!node) {
    node = {
      id: 'rate-limit-gate-001', name: 'Rate Limit Gate',
      type: 'n8n-nodes-base.code', typeVersion: 2, position: [560, 1800], parameters: {},
    };
    wf.nodes.push(node); console.log('✓ added "Rate Limit Gate"'); changed++;
  }
  if (node.parameters.jsCode !== RL_GATE_CODE) { node.parameters.jsCode = RL_GATE_CODE; changed++; console.log('✓ synced "Rate Limit Gate"'); }
})();

(function upsertUnderRateLimit() {
  let node = getNode('Under Rate Limit?');
  const parameters = { conditions: { boolean: [{ value1: '={{ $json._rl_under }}', value2: true }] } };
  if (!node) {
    node = {
      id: 'under-rate-limit-001', name: 'Under Rate Limit?',
      type: 'n8n-nodes-base.if', typeVersion: 1, position: [780, 1800], parameters,
    };
    wf.nodes.push(node); console.log('✓ added "Under Rate Limit?"'); changed++;
  } else { node.parameters = parameters; }
})();

(function upsertRespondRateLimited() {
  let node = getNode('Respond Rate Limited');
  const parameters = {
    respondWith: 'json',
    responseBody: "={{ JSON.stringify({ success: false, code: 'rate_limited', message: 'Ви досягли денного ліміту заявок. Спробуйте, будь ласка, завтра.' }) }}",
    options: { responseCode: 429 },
  };
  if (!node) {
    node = {
      id: 'respond-rate-limited-001', name: 'Respond Rate Limited',
      type: 'n8n-nodes-base.respondToWebhook', typeVersion: 1, position: [1000, 1920], parameters,
    };
    wf.nodes.push(node); console.log('✓ added "Respond Rate Limited"'); changed++;
  } else { node.parameters = parameters; }
})();

// Rewire the Has Profile?=true branch through the rate-limit gate (false branch
// → Respond No Profile stays as-is).
wf.connections['Has Profile?'] = {
  main: [
    [{ node: 'Check Rate Limit', type: 'main', index: 0 }],
    [{ node: 'Respond No Profile', type: 'main', index: 0 }],
  ],
};
wf.connections['Check Rate Limit'] = { main: [[{ node: 'Rate Limit Gate', type: 'main', index: 0 }]] };
wf.connections['Rate Limit Gate'] = { main: [[{ node: 'Under Rate Limit?', type: 'main', index: 0 }]] };
wf.connections['Under Rate Limit?'] = {
  main: [
    [{ node: 'Encrypt Data', type: 'main', index: 0 }],
    [{ node: 'Respond Rate Limited', type: 'main', index: 0 }],
  ],
};

// ── Guard: every connection target must resolve to an existing node ────────────
const names = new Set(wf.nodes.map((n) => n.name));
const dangling = [];
for (const [src, conn] of Object.entries(wf.connections)) {
  if (!names.has(src)) dangling.push(`source "${src}"`);
  for (const outs of conn.main || []) {
    for (const c of outs || []) if (!names.has(c.node)) dangling.push(`${src} → "${c.node}"`);
  }
}
if (dangling.length) {
  console.error('✗ dangling connections:\n  ' + dangling.join('\n  '));
  process.exit(1);
}

// Guard: no real secrets leaked into the committed JSON.
const serialized = JSON.stringify(wf);
if (/eyJ[A-Za-z0-9_-]{20,}/.test(serialized) || /sbp_[A-Za-z0-9]/.test(serialized)) {
  console.error('✗ a secret-looking token is present in the workflow JSON — aborting.');
  process.exit(1);
}

const output = JSON.stringify(wf, null, 2) + '\n';

// --check: drift guard for CI — fail (non-zero) if the committed JSON would change
// (e.g. someone edited preview-excerpt.js without re-running this patcher).
if (process.argv.includes('--check')) {
  const current = readFileSync(WF_FILE, 'utf8');
  if (current !== output) {
    console.error('✗ form-submit.json is out of sync with sync-preview-module-form-submit.mjs.\n  Run: node scripts/sync-preview-module-form-submit.mjs');
    process.exit(1);
  }
  console.log('✓ in sync');
  process.exit(0);
}

writeFileSync(WF_FILE, output, 'utf8');
console.log(`\n${changed ? '✓' : '·'} done (${changed} change${changed === 1 ? '' : 's'}); nodes=${wf.nodes.length}`);
