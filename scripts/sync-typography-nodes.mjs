/**
 * sync-typography-nodes.mjs — add typography phase-2 nodes to form-submit.json.
 *
 * Inserts 3 nodes between "Replace Placeholder" and "Share Document":
 *   Replace Placeholder → Get Document → Build Typography Request → Apply Typography → Share Document
 *
 * Idempotent: exits 0 if the nodes are already present.
 *
 * Usage:
 *   node scripts/sync-typography-nodes.mjs [--check]
 *     --check  exit 1 if out of sync (no write)
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '..');
const wfPath = resolve(repoRoot, 'n8n/workflows/current/form-submit.json');
const checkOnly = process.argv.includes('--check');

const read = (p) => readFileSync(resolve(repoRoot, p), 'utf8').replace(/\r\n/g, '\n');

// ─── Build Typography Request jsCode ─────────────────────────────────────────

const TYPOGRAPHY_CODE = `// ═══════════════════════════════════════════════════════
// Build Typography Request — GENERATED by scripts/sync-typography-nodes.mjs
// Do NOT edit inline: edit n8n/templates/apply-typography.js and re-run.
// ═══════════════════════════════════════════════════════

// Inline mirror: n8n/templates/apply-typography.js
${read('n8n/templates/apply-typography.js')}

const styleHints = $('Build Document').item.json._style_hints || {};
const docBody = $json.body;
const requests = buildTypographyRequests(styleHints, docBody);
console.log('[Typography] styleHints paragraphs:', Object.keys(styleHints).length, '| requests:', requests.length);
return [{ json: { requests } }];
`;

// ─── New nodes ────────────────────────────────────────────────────────────────

const GOOGLE_CRED = { id: 'google-oauth2-001', name: 'Google OAuth2' };

const NEW_NODES = [
  {
    id: 'get-doc-001',
    name: 'Get Document',
    type: 'n8n-nodes-base.httpRequest',
    typeVersion: 4.2,
    position: [3760, 1580],
    parameters: {
      method: 'GET',
      url: "=https://docs.googleapis.com/v1/documents/{{ $('Build Replace Request').item.json._new_doc_id }}",
      authentication: 'predefinedCredentialType',
      nodeCredentialType: 'googleOAuth2Api',
      options: {},
    },
    credentials: { googleOAuth2Api: GOOGLE_CRED },
  },
  {
    id: 'build-typography-001',
    name: 'Build Typography Request',
    type: 'n8n-nodes-base.code',
    typeVersion: 2,
    position: [4000, 1580],
    parameters: { jsCode: TYPOGRAPHY_CODE, mode: 'runOnceForAllItems' },
  },
  {
    id: 'apply-typography-001',
    name: 'Apply Typography',
    type: 'n8n-nodes-base.httpRequest',
    typeVersion: 4.2,
    position: [4240, 1580],
    parameters: {
      method: 'POST',
      url: "=https://docs.googleapis.com/v1/documents/{{ $('Build Replace Request').item.json._new_doc_id }}:batchUpdate",
      authentication: 'predefinedCredentialType',
      nodeCredentialType: 'googleOAuth2Api',
      sendBody: true,
      specifyBody: 'json',
      jsonBody: '={{ JSON.stringify({ requests: $json.requests }) }}',
      options: {},
    },
    credentials: { googleOAuth2Api: GOOGLE_CRED },
  },
];

// ─── Main ─────────────────────────────────────────────────────────────────────

const wfRaw = readFileSync(wfPath, 'utf8');
const wf = JSON.parse(wfRaw);

// Idempotency check
if (wf.nodes.some((n) => n.name === 'Get Document')) {
  // Already present — check if Build Typography Request code is in sync
  const btNode = wf.nodes.find((n) => n.name === 'Build Typography Request');
  if (btNode && btNode.parameters.jsCode === TYPOGRAPHY_CODE) {
    console.log('✅ Typography nodes already in sync.');
    process.exit(0);
  }
  if (checkOnly) {
    console.error('❌ Build Typography Request is OUT OF SYNC. Run: node scripts/sync-typography-nodes.mjs');
    process.exit(1);
  }
  // Update only the jsCode
  btNode.parameters.jsCode = TYPOGRAPHY_CODE;
  writeFileSync(wfPath, JSON.stringify(wf, null, 2) + '\n', 'utf8');
  console.log('✅ Build Typography Request jsCode updated.');
  console.log('Next: node scripts/deploy-workflow.mjs form-submit');
  process.exit(0);
}

if (checkOnly) {
  console.error('❌ Typography nodes missing. Run: node scripts/sync-typography-nodes.mjs');
  process.exit(1);
}

// Shift existing downstream nodes: Share Document and Send Doc Link move right
const SHIFT_NODES = ['Share Document', 'Send Doc Link'];
const SHIFT_X = 720; // 3 new nodes × 240px spacing
for (const node of wf.nodes) {
  if (SHIFT_NODES.includes(node.name)) {
    node.position[0] += SHIFT_X;
  }
}

// Add new nodes
wf.nodes.push(...NEW_NODES);

// Rewire connections
// Before: Replace Placeholder → Share Document
// After:  Replace Placeholder → Get Document → Build Typography Request → Apply Typography → Share Document
wf.connections['Replace Placeholder'] = {
  main: [[{ node: 'Get Document', type: 'main', index: 0 }]],
};
wf.connections['Get Document'] = {
  main: [[{ node: 'Build Typography Request', type: 'main', index: 0 }]],
};
wf.connections['Build Typography Request'] = {
  main: [[{ node: 'Apply Typography', type: 'main', index: 0 }]],
};
wf.connections['Apply Typography'] = {
  main: [[{ node: 'Share Document', type: 'main', index: 0 }]],
};

writeFileSync(wfPath, JSON.stringify(wf, null, 2) + '\n', 'utf8');
console.log('✅ Typography nodes added to form-submit.json (+3 nodes, Share Document/Send Doc Link shifted).');
console.log('Next:');
console.log('  1. node scripts/sync-build-document-node.mjs   # update Build Document to return _style_hints');
console.log('  2. node scripts/deploy-workflow.mjs form-submit');
