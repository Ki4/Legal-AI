/**
 * sync-user-error-feedback.mjs — patch form-submit.json so the CLIENT (not just
 * the admin) is notified when async document generation fails.
 *
 * Background: everything after "Respond OK" runs asynchronously
 *   Copy Template → Build Replace Request → Replace Placeholder → Get Document
 *   → Build Typography Request → Apply Typography → Share Document → Send Doc Link
 * A failure in that chain only ever reached the catch-all Error Trigger →
 * admin alert. The Error Trigger runs in a SEPARATE execution with no access to
 * the user's chat id, so the client stayed forever on "Документ готується… ⏳"
 * (real incident: case 56e84825). See docs/architecture/TELEGRAM-BOT-GUIDE.md §3.
 *
 * Fix (idempotent):
 *   1. Set onError:'continueErrorOutput' on the 7 generation nodes
 *      (Copy Template … Share Document) — NOT on Send Doc Link (its failure means
 *      the doc IS ready, a semantically different case left out of scope).
 *   2. Add 2 nodes:
 *        - "Format Gen Failure" (Code, GENERATED from n8n/templates/format-gen-failure.js)
 *        - "Notify User Failed" (Telegram → the client)
 *   3. Wire each generation node's ERROR output (main[1]) → Format Gen Failure
 *      → Notify User Failed → (existing) Send Admin Alert.
 *      This branch runs in the MAIN execution, so $('Validate')._user_id and the
 *      case id resolve directly — no n8n-API lookup, no extra secret.
 *      Notify User Failed uses onError:'continueRegularOutput' so a send failure
 *      (e.g. user blocked the bot) still lets the admin alert through.
 *
 * Usage:
 *   node scripts/sync-user-error-feedback.mjs [--check]
 *     --check   exit 1 if not patched; exit 0 if in sync
 *
 * Run order: this script → node scripts/deploy-workflow.mjs form-submit
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot  = resolve(__dirname, '..');
const wfPath    = resolve(repoRoot, 'n8n/workflows/current/form-submit.json');
const checkOnly = process.argv.includes('--check');

const read = (p) => readFileSync(resolve(repoRoot, p), 'utf8').replace(/\r\n/g, '\n');

// Generation nodes that run AFTER Respond OK and can fail silently.
const GEN_NODES = [
  'Copy Template',
  'Build Replace Request',
  'Replace Placeholder',
  'Get Document',
  'Build Typography Request',
  'Apply Typography',
  'Share Document',
];

const TELEGRAM_CREDS = { telegramApi: { id: '6OfTH9OBUuEgKALQ', name: 'Telegram account' } };

// ─── Generated Code node body (mirror: n8n/templates/format-gen-failure.js) ────
const FORMAT_GEN_FAILURE_CODE = [
  '// ═══════════════════════════════════════════════════════',
  '// Format Gen Failure — GENERATED by scripts/sync-user-error-feedback.mjs',
  '// Edit n8n/templates/format-gen-failure.js and re-run this script.',
  '// ═══════════════════════════════════════════════════════',
  '',
  read('n8n/templates/format-gen-failure.js'),
  '',
  '// n8n entry point — runs in the MAIN execution (error output of a gen node):',
  "const caseId = (() => { try { return $('Insert Case').item.json.id; } catch (_) { return null; } })();",
  "const serviceTitle = (() => { try { return $('Get Service').item.json.title; } catch (_) { return null; } })();",
  "const userId = (() => { try { return $('Validate').item.json._user_id; } catch (_) { return null; } })();",
  'const executionId = (typeof $execution !== \'undefined\' && $execution) ? $execution.id : null;',
  'const error = ($json && ($json.error || $json.lastError)) || null;',
  'return [{ json: {',
  '  text: formatGenFailure({ error, executionId, caseId, serviceTitle }),',
  '  _user_text: userFailureMessage(caseId, serviceTitle),',
  '  _user_id: userId,',
  '} }];',
].join('\n');

// Client failure card — HTML + a single navigation button (handled by main-bot).
const NOTIFY_USER_FAILED_PARAMS = {
  chatId: '={{ $json._user_id }}',
  text:   '={{ $json._user_text }}',
  replyMarkup: 'inlineKeyboard',
  inlineKeyboard: {
    rows: [
      { row: { buttons: [{ text: '➕ Інша послуга', additionalFields: { callback_data: 'show_menu' } }] } },
    ],
  },
  additionalFields: { appendAttribution: false, parse_mode: 'HTML' },
};

const NEW_NODES = [
  {
    id:          'format-gen-failure-001',
    name:        'Format Gen Failure',
    type:        'n8n-nodes-base.code',
    typeVersion: 2,
    position:    [3520, 2000],
    parameters:  { jsCode: FORMAT_GEN_FAILURE_CODE },
  },
  {
    id:          'notify-user-failed-001',
    name:        'Notify User Failed',
    type:        'n8n-nodes-base.telegram',
    typeVersion: 1.2,
    position:    [3760, 2000],
    onError:     'continueRegularOutput', // a failed send must not block the admin alert
    parameters:  NOTIFY_USER_FAILED_PARAMS,
    credentials: TELEGRAM_CREDS,
  },
];

// ─── Main ──────────────────────────────────────────────────────────────────────
const wf = JSON.parse(readFileSync(wfPath, 'utf8'));

// Guard: the generation chain must exist.
const missing = GEN_NODES.filter(name => !wf.nodes.some(n => n.name === name));
if (missing.length) {
  console.error('❌ Missing generation nodes: ' + missing.join(', '));
  process.exit(1);
}
if (!wf.nodes.some(n => n.name === 'Send Admin Alert')) {
  console.error('❌ "Send Admin Alert" not found — run the base error-handling sync first.');
  process.exit(1);
}

const alreadyPatched = wf.nodes.some(n => n.name === 'Notify User Failed');

/** Set onError + the error-output (main[1]) connection on every generation node. */
function wireErrorOutputs() {
  let touched = 0;
  for (const name of GEN_NODES) {
    const node = wf.nodes.find(n => n.name === name);
    if (node.onError !== 'continueErrorOutput') { node.onError = 'continueErrorOutput'; touched++; }
    const conn = (wf.connections[name] ||= { main: [] });
    conn.main[0] ||= [];
    const errOut = [{ node: 'Format Gen Failure', type: 'main', index: 0 }];
    if (JSON.stringify(conn.main[1]) !== JSON.stringify(errOut)) { conn.main[1] = errOut; touched++; }
  }
  return touched;
}

/**
 * Format Gen Failure FANS OUT to both Notify User Failed (the client) AND
 * Send Admin Alert (admin) in parallel — NOT sequentially. Sequential wiring
 * fails the admin leg: it would receive Notify User Failed's Telegram-response
 * output, which has no usable `text` (verified live: "Bad request" + a spurious
 * Error Trigger fire). Notify User Failed is a leaf (onError:continueRegularOutput
 * already guards a failed user send from breaking the run).
 */
function wireFanout() {
  let touched = 0;
  const fanout = { main: [[
    { node: 'Notify User Failed', type: 'main', index: 0 },
    { node: 'Send Admin Alert',   type: 'main', index: 0 },
  ]] };
  if (JSON.stringify(wf.connections['Format Gen Failure']) !== JSON.stringify(fanout)) {
    wf.connections['Format Gen Failure'] = fanout; touched++;
  }
  if (wf.connections['Notify User Failed']) { delete wf.connections['Notify User Failed']; touched++; }
  return touched;
}

if (alreadyPatched) {
  if (checkOnly) { console.log('✅ User-error-feedback already present — in sync.'); process.exit(0); }
  // Re-run: refresh generated code + re-assert wiring.
  let changed = false;
  const fmt = wf.nodes.find(n => n.name === 'Format Gen Failure');
  if (fmt && fmt.parameters.jsCode !== FORMAT_GEN_FAILURE_CODE) {
    console.log(`  ↻ Refreshing "Format Gen Failure" (${fmt.parameters.jsCode.length} → ${FORMAT_GEN_FAILURE_CODE.length} chars)`);
    fmt.parameters.jsCode = FORMAT_GEN_FAILURE_CODE;
    changed = true;
  }
  const nuf = wf.nodes.find(n => n.name === 'Notify User Failed');
  if (nuf && JSON.stringify(nuf.parameters) !== JSON.stringify(NOTIFY_USER_FAILED_PARAMS)) {
    console.log('  ↻ Reconciling "Notify User Failed" (HTML card + button)');
    nuf.parameters = NOTIFY_USER_FAILED_PARAMS;
    changed = true;
  }
  if (wireErrorOutputs() > 0) { console.log('  ↻ Re-asserted onError + error-output wiring'); changed = true; }
  if (wireFanout() > 0) { console.log('  ↻ Re-asserted Format Gen Failure fan-out (user + admin)'); changed = true; }
  if (!changed) { console.log('✅ Already in sync.'); process.exit(0); }
  writeFileSync(wfPath, JSON.stringify(wf, null, 2) + '\n', 'utf8');
  console.log('✅ Refreshed. Next: node scripts/deploy-workflow.mjs form-submit');
  process.exit(0);
}

if (checkOnly) {
  console.error('❌ User-error-feedback NOT in form-submit.json. Run: node scripts/sync-user-error-feedback.mjs');
  process.exit(1);
}

// 1. Add the 2 new nodes.
wf.nodes.push(...NEW_NODES);

// 2. onError + error-output connections on the generation nodes.
wireErrorOutputs();

// 3. Format Gen Failure fans out to Notify User Failed (client) + Send Admin Alert.
wireFanout();

writeFileSync(wfPath, JSON.stringify(wf, null, 2) + '\n', 'utf8');

console.log('✅ Client generation-failure feedback patched into form-submit.json:');
console.log('   +2 nodes: Format Gen Failure, Notify User Failed');
console.log('   onError:continueErrorOutput on: ' + GEN_NODES.join(', '));
console.log('   error outputs → Format Gen Failure → Notify User Failed → Send Admin Alert');
console.log('');
console.log('Next: node scripts/deploy-workflow.mjs form-submit');
