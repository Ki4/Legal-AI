// sync-webhook-dedup.mjs — idempotent patcher for n8n/workflows/current/main-bot.json
//
// IMPROVEMENTS #83: Telegram re-delivers an update when it doesn't get a fast
// 200 (e.g. during a transient error like session 39's 500), so the SAME
// message gets processed twice. This inserts a "Dedup Update" Code node right
// after the Telegram Trigger that drops a repeat update_id, using the workflow's
// global static data as a small TTL map.
//
//   Telegram Trigger ─▶ Dedup Update ─▶ Normalize
//                         (returns [] for a duplicate → flow stops)
//
// Anti-drift: the dedup core is GENERATED from n8n/templates/dedup-update.js
// (single source of truth, unit-tested). Edit that file and re-run this script.
//
//   node scripts/deploy-workflow.mjs main-bot --check
//   node scripts/deploy-workflow.mjs main-bot

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const WF_FILE = resolve(ROOT, 'n8n/workflows/current/main-bot.json');
const read = (p) => readFileSync(resolve(ROOT, p), 'utf8').replace(/\r\n/g, '\n');

const wf = JSON.parse(readFileSync(WF_FILE, 'utf8'));
const byName = (name) => wf.nodes.find((n) => n.name === name);

let changed = 0;
const note = (msg) => console.log(msg);

// ── Generated Dedup Update jsCode ─────────────────────────────────────────────
const DEDUP_CODE = [
  '// ═══════════════════════════════════════════════════════',
  '// Dedup Update — GENERATED by scripts/sync-webhook-dedup.mjs',
  '// Edit n8n/templates/dedup-update.js and re-run this script.',
  '// ═══════════════════════════════════════════════════════',
  '',
  '// Core function (mirror: n8n/templates/dedup-update.js)',
  read('n8n/templates/dedup-update.js'),
  '',
  '// n8n entry point:',
  "const staticData = $getWorkflowStaticData('global');",
  'if (!staticData.seenUpdates) staticData.seenUpdates = {};',
  'const update = $input.first().json;',
  'const { isDuplicate } = dedupUpdate(staticData.seenUpdates, update.update_id, Date.now());',
  '// Duplicate → return no items so the rest of the flow does not run again.',
  'if (isDuplicate) return [];',
  'return [{ json: update }];',
].join('\n');

// ── 1. Dedup Update node ──────────────────────────────────────────────────────
const existing = byName('Dedup Update');
if (existing) {
  if (existing.parameters.jsCode !== DEDUP_CODE) {
    existing.parameters.jsCode = DEDUP_CODE;
    note('✓ Dedup Update: jsCode refreshed from template');
    changed++;
  } else {
    note('· Dedup Update already up to date (skip)');
  }
} else {
  // Place just left of Normalize so the chain reads left→right.
  const norm = byName('Normalize');
  const pos = norm ? [norm.position[0] - 220, norm.position[1]] : [-1840, 1600];
  wf.nodes.push({
    id: 'main-bot-dedup-update',
    name: 'Dedup Update',
    type: 'n8n-nodes-base.code',
    typeVersion: 2,
    position: pos,
    parameters: { jsCode: DEDUP_CODE },
  });
  note('✓ added node "Dedup Update"');
  changed++;
}

// ── 2. Rewire: Telegram Trigger → Dedup Update → Normalize ────────────────────
function setConnection(nodeName, def) {
  const before = JSON.stringify(wf.connections[nodeName] ?? null);
  const after = JSON.stringify(def);
  if (before === after) {
    note(`· connections["${nodeName}"] already correct (skip)`);
    return;
  }
  wf.connections[nodeName] = def;
  note(`✓ connections["${nodeName}"] rewired`);
  changed++;
}

setConnection('Telegram Trigger', { main: [[{ node: 'Dedup Update', type: 'main', index: 0 }]] });
setConnection('Dedup Update', { main: [[{ node: 'Normalize', type: 'main', index: 0 }]] });

writeFileSync(WF_FILE, JSON.stringify(wf, null, 2) + '\n', 'utf8');
console.log(`\n${changed ? '✓' : '·'} main-bot.json written (${changed} change${changed === 1 ? '' : 's'}).`);
console.log('Next: node scripts/deploy-workflow.mjs main-bot --check');
